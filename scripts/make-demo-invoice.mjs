/**
 * Generates the sample invoice embedded in the app.
 *
 * The signature here is REAL: it is produced by a throwaway key and recovers
 * correctly, so the payer-side verification does genuine work when a judge opens
 * the sample. Nothing is mocked.
 *
 * The key is a publicly known development key that has never held funds and is
 * never used to sign anything but this sample. Do not send tokens to it.
 *
 * Run: node scripts/make-demo-invoice.mjs
 */
import { privateKeyToAccount } from 'viem/accounts'
import { keccak256, toHex } from 'viem'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const outFile = resolve(here, '../src/demo/demoInvoice.ts')

const DEMO_KEY =
  '0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d'

const CANDIDATE_WIF = '0x5173b8eA6923c2d40267890D45C46a3480954773'
const CHAIN_ID = 4663

const account = privateKeyToAccount(DEMO_KEY)

const now = Math.floor(Date.now() / 1000)
const reference = 'October build support'

const payload = {
  payee: account.address,
  token: CANDIDATE_WIF,
  amount: (8400n * 10n ** 18n).toString(),
  chainId: CHAIN_ID,
  // Fixed identifier so regenerating the sample does not churn the diff.
  invoiceId: keccak256(toHex('payeestamp-demo-invoice-027')),
  issuedAt: now,
  expiresAt: now + 60 * 60 * 24 * 30,
  referenceHash: keccak256(toHex(reference)),
  reference,
}

const signature = await account.signTypedData({
  domain: { name: 'PayeeStamp', version: '1', chainId: CHAIN_ID },
  types: {
    Invoice: [
      { name: 'payee', type: 'address' },
      { name: 'token', type: 'address' },
      { name: 'amount', type: 'uint256' },
      { name: 'chainId', type: 'uint256' },
      { name: 'invoiceId', type: 'bytes32' },
      { name: 'issuedAt', type: 'uint256' },
      { name: 'expiresAt', type: 'uint256' },
      { name: 'referenceHash', type: 'bytes32' },
    ],
  },
  primaryType: 'Invoice',
  message: {
    payee: payload.payee,
    token: payload.token,
    amount: BigInt(payload.amount),
    chainId: BigInt(payload.chainId),
    invoiceId: payload.invoiceId,
    issuedAt: BigInt(payload.issuedAt),
    expiresAt: BigInt(payload.expiresAt),
    referenceHash: payload.referenceHash,
  },
})

const banner = `/**
 * GENERATED by scripts/make-demo-invoice.mjs — do not edit by hand.
 *
 * The signature below is real and recovers to the payee address. No funds have
 * moved and no wallet was funded to produce it. This exists so the payer-side
 * verification can be exercised without a wallet.
 */
import type { SignedInvoice } from '../types'

export const DEMO_INVOICE: SignedInvoice | null = `

const body = JSON.stringify({ payload, signature }, null, 2)

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, `${banner}${body}\n`, 'utf8')

console.log(`Wrote ${outFile}`)
console.log(`payee:     ${account.address}`)
console.log(`signature: ${signature.slice(0, 20)}…`)
